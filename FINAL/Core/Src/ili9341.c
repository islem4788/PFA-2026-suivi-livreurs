/* ── Fill screen ───────────────────────────────────────── */
void LCD_FillScreen(uint16_t color)
{
    LCD_FillRect(0, 0, LCD_WIDTH, LCD_HEIGHT, color);
}

/* ── Fill rectangle ────────────────────────────────────── */
void LCD_FillRect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;
    if (x + w > LCD_WIDTH)  w = LCD_WIDTH - x;
    if (y + h > LCD_HEIGHT) h = LCD_HEIGHT - y;

    LCD_SetWindow(x, y, x + w - 1, y + h - 1);

    uint8_t buf[2] = { color >> 8, color & 0xFF };
    LCD_DC_DATA();
    LCD_CS_LOW();
    for (uint32_t i = 0; i < (uint32_t)w * h; i++) {
        HAL_SPI_Transmit(lcd_spi, buf, 2, 10);
    }
    LCD_CS_HIGH();
}

/* ── Draw single character (8x16) ──────────────────────── */
void LCD_DrawChar(uint16_t x, uint16_t y, char c, uint16_t fg, uint16_t bg)
{
    if (c < 32 || c > 122) c = '?';
    const uint8_t *glyph = font_8x16[c - 32];

    LCD_SetWindow(x, y, x + 7, y + 15);

    uint8_t buf[2];
    LCD_DC_DATA();
    LCD_CS_LOW();
    for (int row = 0; row < 16; row++) {
        uint8_t line = glyph[row];
        for (int col = 7; col >= 0; col--) {
            uint16_t color = (line & (1 << col)) ? fg : bg;
            buf[0] = color >> 8;
            buf[1] = color & 0xFF;
            HAL_SPI_Transmit(lcd_spi, buf, 2, 10);
        }
    }
    LCD_CS_HIGH();
}

/* ── Draw string ───────────────────────────────────────── */
void LCD_DrawString(uint16_t x, uint16_t y, const char *str, uint16_t fg, uint16_t bg)
{
    while (*str) {
        if (x + 8 > LCD_WIDTH) {
            x = 0;
            y += 16;
        }
        if (y + 16 > LCD_HEIGHT) break;
        LCD_DrawChar(x, y, *str, fg, bg);
        x += 8;
        str++;
    }
}

/* ── Draw large string (doubled: 16x32 effective) ──────── */
void LCD_DrawStringLarge(uint16_t x, uint16_t y, const char *str, uint16_t fg, uint16_t bg)
{
    while (*str) {
        if (*str < 32 || *str > 122) { str++; continue; }
        const uint8_t *glyph = font_8x16[*str - 32];

        LCD_SetWindow(x, y, x + 15, y + 31);
        uint8_t buf[2];
        LCD_DC_DATA();
        LCD_CS_LOW();
        for (int row = 0; row < 16; row++) {
            uint8_t line = glyph[row];
            /* Each row drawn twice (vertical double) */
            for (int pass = 0; pass < 2; pass++) {
                for (int col = 7; col >= 0; col--) {
                    uint16_t color = (line & (1 << col)) ? fg : bg;
                    buf[0] = color >> 8;
                    buf[1] = color & 0xFF;
                    /* Each pixel drawn twice (horizontal double) */
                    HAL_SPI_Transmit(lcd_spi, buf, 2, 10);
                    HAL_SPI_Transmit(lcd_spi, buf, 2, 10);
                }
            }
        }
        LCD_CS_HIGH();

        x += 16;
        str++;
    }
}

/* ── Draw horizontal line ──────────────────────────────── */
void LCD_DrawHLine(uint16_t x, uint16_t y, uint16_t w, uint16_t color)
{
    LCD_FillRect(x, y, w, 1, color);
}

/* ── Draw value bar (horizontal bar graph) ─────────────── */
void LCD_DrawBar(uint16_t x, uint16_t y, uint16_t max_w, uint16_t h,
                 float value, float min_val, float max_val,
                 uint16_t fg, uint16_t bg)
{
    /* Clamp value */
    if (value < min_val) value = min_val;
    if (value > max_val) value = max_val;

    /* Calculate bar width */
    float ratio = (value - min_val) / (max_val - min_val);
    uint16_t bar_w = (uint16_t)(ratio * max_w);

    /* Draw filled portion */
    if (bar_w > 0) LCD_FillRect(x, y, bar_w, h, fg);
    /* Draw empty portion */
    if (bar_w < max_w) LCD_FillRect(x + bar_w, y, max_w - bar_w, h, bg);
}
